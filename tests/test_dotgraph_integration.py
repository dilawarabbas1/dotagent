    from dotagent.dotgraph_probe import ensure_gitignored
    for content in (".dotgraph\n", "/.dotgraph/\n", ".dotgraph # tracked elsewhere\n"):
        gi = tmp_path / ".gitignore"
        gi.write_text(content)
        msg = ensure_gitignored(tmp_path)
        assert msg == "", f"variant '{content.strip()}' should not append again"


