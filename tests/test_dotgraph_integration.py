def _install_dotgraph_shim(
    tmp_path: Path,
    *,
    version_out: str = "dotgraph, version 0.1.8",
    status_json: dict | None = None,
    status_exit: int = 0,
    emit_docs_exit: int = 0,
    emit_docs_writes: list[str] | None = None,
    crash_on: str | None = None,
    monkeypatch,
) -> Path:
    """Create a shim `dotgraph` binary on PATH that emulates dotgraph's
    surface. Returns the bin directory.

    `version_out` — what `dotgraph --version` prints to stdout.
    `status_json` — dict to emit on `dotgraph status --json`. If None,
        the default {"files":42,"dirty_files":0,"nodes":7361,
        "edges":12000,"unresolved":3} is used.
    `status_exit` — exit code for `status`.
    `emit_docs_exit` — exit code for `emit-docs`.
    `emit_docs_writes` — list of relative paths to write under the cwd's
        docs/ directory when emit-docs runs (simulates real behavior).
        Defaults to ["dependency-map.md"].
    `crash_on` — if set, the shim raises an error on that subcommand
        (`status`, `emit-docs`, or `--version`).
    """
    bin_dir = tmp_path / "fake-bin"
    bin_dir.mkdir(exist_ok=True)

    status_dict = status_json if status_json is not None else {
        "files": 42, "dirty_files": 0, "nodes": 7361,
        "edges": 12000, "unresolved": 3, "db": ".dotgraph/graph.db",
    }
    writes = emit_docs_writes if emit_docs_writes is not None else ["dependency-map.md"]

    script = f"""#!/usr/bin/env python3
import json
import os
import sys

argv = sys.argv[1:]
if {crash_on!r}:
    if (argv and argv[0] == {crash_on!r}) or ({crash_on!r} == "--version" and argv == ["--version"]):
        print("boom: simulated dotgraph crash", file=sys.stderr)
        sys.exit(2)

if argv == ["--version"]:
    print({version_out!r})
    sys.exit(0)
if argv[:1] == ["status"]:
    if "--json" in argv:
        print(json.dumps({status_dict!r}))
    else:
        for k, v in {status_dict!r}.items():
            print(f"{{k:14s}} {{v}}")
    sys.exit({status_exit})
if argv[:1] == ["emit-docs"]:
    docs_dir = os.path.join(os.getcwd(), "docs")
    os.makedirs(docs_dir, exist_ok=True)
    for rel in {writes!r}:
        full = os.path.join(docs_dir, rel)
        with open(full, "w") as fh:
            fh.write("<!-- generated by fake dotgraph -->\\nshim content\\n")
        print(f"wrote {{full}}")
    sys.exit({emit_docs_exit})
print(f"unknown subcommand: {{argv}}", file=sys.stderr)
sys.exit(64)
"""
    bin_path = bin_dir / "dotgraph"
    bin_path.write_text(script)
    bin_path.chmod(bin_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    # Prepend to PATH so this shim wins.
    existing = os.environ.get("PATH", "")
    monkeypatch.setenv("PATH", f"{bin_dir}{os.pathsep}{existing}")
    return bin_dir


def _make_dotgraph_db(repo: Path) -> Path:
    (repo / ".dotgraph").mkdir(parents=True, exist_ok=True)
    db = repo / ".dotgraph" / "graph.db"
    db.write_bytes(b"")
    return db


def _make_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    paths = Paths(repo=repo)
    scaffold_agent_dir(paths)
    dump_yaml(paths.config, merge_defaults({"project": {"name": "T"}}))
    # Mark the .agent/ schema as current — structure check would otherwise
    # fail with `.agent/.version` missing → doctor would exit 1.
    from dotagent.canonical_structure import CURRENT_SCHEMA_VERSION
    (paths.agent / ".version").write_text(CURRENT_SCHEMA_VERSION + "\n")
    return repo


