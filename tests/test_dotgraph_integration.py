def test_sync_respects_skip_empty_config_knob(tmp_path: Path, monkeypatch):
    """v0.5.4 — `dotagent.dotgraph.emit_docs.skip_empty: false` in
    config.yaml forces emit-docs to write all 5 files."""
    import yaml as _yaml
    repo = _make_repo(tmp_path)
    cfg_path = repo / ".agent" / "config.yaml"
    cfg = _yaml.safe_load(cfg_path.read_text())
    cfg.setdefault("dotagent", {}).setdefault("dotgraph", {})[
        "emit_docs"] = {"skip_empty": False}
    cfg_path.write_text(_yaml.safe_dump(cfg))

    _install_dotgraph_shim(
        tmp_path,
        emit_docs_writes=["dependency-map.md", "kafka-topics.md"],
        monkeypatch=monkeypatch,
    )
    _make_dotgraph_db(repo)
    monkeypatch.setenv("ALL_EMPTY", "1")  # would skip kafka by default
    monkeypatch.chdir(repo)

    result = CliRunner().invoke(sync, [])
    assert result.exit_code == 0, result.output
    # With skip_empty=false override, NOTHING gets dropped
    assert "skipped" not in result.output
    assert (repo / "docs" / "kafka-topics.md").exists()


