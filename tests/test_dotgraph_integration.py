"""Tests for the dotgraph probe + doctor JSON + sync emit-docs pre-step.

dotgraph is an external tool. We don't depend on it being installed in the
test runner. Instead each test shims a fake `dotgraph` binary on PATH that
behaves the way the test needs (--version returns text, status returns JSON,
emit-docs writes a docs/dependency-map.md file, etc.).

Coverage matrix:
- probe: installed × db_present × dirty matrix
- probe: dotgraph crashes → error captured, stale=True
- probe: bad JSON → error captured
- doctor JSON: gains `dotgraph` envelope; existing `diagnoses` list still there
- doctor text: emits the one-line dotgraph summary
- sync: emit-docs runs when db present
- sync: emit-docs skipped when db absent
- sync: emit-docs skipped when --skip-dotgraph
- sync: emit-docs failure is logged but doesn't break sync
"""

