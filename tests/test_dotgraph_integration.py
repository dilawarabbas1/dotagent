def test_probe_dotgraph_not_on_path(tmp_path: Path, monkeypatch):
    """Without dotgraph on PATH → installed=False, every other field null."""
    # Clear PATH so dotgraph definitely isn't found.
    monkeypatch.setenv("PATH", "/nonexistent")
    info = probe(tmp_path)
    assert info.installed is False
    assert info.version is None
    assert info.db_present is False
    assert info.dirty_files is None
    assert info.last_indexed is None
    assert info.stale is False
    assert info.error is None


def test_probe_installed_no_db(tmp_path: Path, monkeypatch):
    """dotgraph on PATH, but no `.dotgraph/graph.db` → installed=True,
    db_present=False, other status fields null. No subprocess call for
    status (saves time on cold projects)."""
    _install_dotgraph_shim(tmp_path, monkeypatch=monkeypatch)
    info = probe(tmp_path)
    assert info.installed is True
    assert info.version == "0.1.8"
    assert info.db_present is False
    assert info.dirty_files is None


def test_probe_installed_db_present_clean(tmp_path: Path, monkeypatch):
    _install_dotgraph_shim(tmp_path, monkeypatch=monkeypatch)
    _make_dotgraph_db(tmp_path)
    info = probe(tmp_path)
    assert info.installed is True
    assert info.version == "0.1.8"
    assert info.db_present is True
    assert info.dirty_files == 0
    assert info.nodes == 7361
    assert info.edges == 12000
    assert info.unresolved == 3
    assert info.files == 42
    assert info.stale is False
    assert info.error is None
    # last_indexed not in dotgraph status JSON → null
    assert info.last_indexed is None


def test_probe_dirty_files_marks_stale(tmp_path: Path, monkeypatch):
    _install_dotgraph_shim(
        tmp_path,
        status_json={
            "files": 42, "dirty_files": 7, "nodes": 7361,
            "edges": 12000, "unresolved": 3,
        },
        monkeypatch=monkeypatch,
    )
    _make_dotgraph_db(tmp_path)
    info = probe(tmp_path)
    assert info.dirty_files == 7
    assert info.stale is True


def test_probe_status_crash_captures_error(tmp_path: Path, monkeypatch):
    """dotgraph status crash → installed=True, db_present=True, error set,
    stale=True (conservative default)."""
    _install_dotgraph_shim(
        tmp_path, status_exit=1, monkeypatch=monkeypatch,
    )
    _make_dotgraph_db(tmp_path)
    info = probe(tmp_path)
    assert info.installed is True
    assert info.db_present is True
    assert info.error is not None
    assert "exit=1" in info.error
    assert info.stale is True


def test_probe_bad_json_captures_error(tmp_path: Path, monkeypatch):
    """status returns junk on stdout → JSON parse error captured."""
    bin_dir = tmp_path / "fake-bin"
    bin_dir.mkdir()
    bin_path = bin_dir / "dotgraph"
    bin_path.write_text(
        "#!/usr/bin/env python3\n"
        "import sys\n"
        "if sys.argv[1:] == ['--version']:\n"
        "    print('dotgraph, version 0.1.8')\n"
        "    sys.exit(0)\n"
        "if sys.argv[1:2] == ['status']:\n"
        "    print('not json {{')\n"
        "    sys.exit(0)\n"
        "sys.exit(64)\n"
    )
    bin_path.chmod(0o755)
    monkeypatch.setenv("PATH", f"{bin_dir}{os.pathsep}{os.environ.get('PATH', '')}")

    _make_dotgraph_db(tmp_path)
    info = probe(tmp_path)
    assert info.error is not None
    assert "parse error" in info.error
    assert info.stale is True


