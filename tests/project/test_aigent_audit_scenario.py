"""End-to-end regression test mirroring the Aigent project audit scenario.

User audit (2026-05-20) revealed several real gaps when running against a
real layered-tier project:

1. Brief parser couldn't read `**OBJ-01 · Title**:` shape (fixed in 0.4.4)
2. plan.yaml missing top-level name/goal/success_criteria → empty dashboard titles
3. SCOPE.md regenerate would HOLLOW the file because render_scope() reads
   the missing fields without fallback
4. traceability.audit_feat_to_module read only module.yaml::implements_features,
   ignoring plan.yaml::features_to_modules
5. Frozen contracts missing FEAT-NN treated as fail (should be info — frozen
   = immutable, can't be edited)
6. No regenerate command — user had to find an unrelated state-changing op
   to trigger SCOPE.md regen

This test asserts all six are fixed and stay fixed.
"""

