# Fix 2/3: full layered-tier scenario — plan.yaml thin + brief populated
# ---------------------------------------------------------------------------

def test_full_aigent_scenario_end_to_end(tmp_path: Path):
    """End-to-end mirroring the user's exact failure mode:

    - plan.yaml has no top-level name/goal/description
    - plan.yaml has features_to_modules (layered-tier shape)
    - brief uses **OBJ-01 · Title**: shape
    - module.yaml files have NO implements_features

    After 0.4.5 all three audits should be either clean or info-only.
    """
    paths = Paths(repo=tmp_path)
    scaffold_agent_dir(paths)
    dump_yaml(paths.config, merge_defaults({"project": {"name": "Aigent"}}))
    (tmp_path / ".agent" / "project_brief.md").write_text(_AIGENT_BRIEF)

    # plan.yaml in layered-tier shape: no name/goal/etc, has features_to_modules
    dump_yaml(paths.project_plan, {
        "brief_version": 2,
        "brief_features_covered": ["FEAT-01", "FEAT-02"],
        "features_to_modules": {"FEAT-01": ["M01"], "FEAT-02": ["M02"]},
        "modules": {
            "M01": {"state": "planned"},
            "M02": {"state": "in_progress"},
        },
        "repos": [
            {"id": "backend", "path": "./backend",
             "remote": "git@x:y.git", "default_branch": "main", "role": "api"},
        ],
    })

    project = load_project(paths)
    brief = parse(_AIGENT_BRIEF)
    modules = list(project.modules.values())

    # 1. Brief parses with all IDs
    assert brief.objective_ids == ["OBJ-01", "OBJ-02"]
    assert brief.feature_ids == ["FEAT-01", "FEAT-02"]

    # 2. SCOPE.md regenerates with brief fallback (not hollow)
    scope = render_scope(project, brief=brief)
    assert "Aigent" in scope                       # name from brief
    assert "Universal AI chat layer" in scope      # goal from brief.vision
    assert "(unset" not in scope.split("##")[0]    # title isn't unset

    # 3. FEAT→Module audit passes via plan.yaml::features_to_modules
    findings = audit_feat_to_module(brief, project, modules)
    feat_findings = [f for f in findings if f.code == "feat-no-module"]
    assert feat_findings == [], (
        "After 0.4.5, FEATs covered by features_to_modules shouldn't "
        f"be flagged as unmapped. Got: {feat_findings}"
    )


