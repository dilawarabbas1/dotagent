def test_regenerate_command_writes_scope_with_brief_fallback(tmp_path: Path):
    """Test the actual CLI command works on a thin plan.yaml + populated brief.

    This is the failure case the user hit: 'dotagent sync' didn't regenerate
    SCOPE.md, and there was no other command to trigger it without changing
    state. The new `dotagent project regenerate` fills that gap.
    """
    import os
    from click.testing import CliRunner
    from dotagent.cli import main

    paths = Paths(repo=tmp_path)
    scaffold_agent_dir(paths)
    dump_yaml(paths.config, merge_defaults({"project": {"name": "Aigent"}}))
    (tmp_path / ".agent" / ".version").write_text("0.4.0\n")
    (tmp_path / ".agent" / "project_brief.md").write_text(_AIGENT_BRIEF)
    dump_yaml(paths.project_plan, {
        "brief_features_covered": ["FEAT-01"],
        "features_to_modules": {"FEAT-01": ["M01"]},
        "modules": {"M01": {"state": "planned"}},
        "repos": [],
    })

    runner = CliRunner()
    orig = os.getcwd()
    os.chdir(tmp_path)
    try:
        result = runner.invoke(main, ["project", "regenerate"], catch_exceptions=False)
    finally:
        os.chdir(orig)

    assert result.exit_code == 0, result.output
    assert paths.project_scope_md.exists()
    body = paths.project_scope_md.read_text()
    # Banner present (fixes the SCOPE.md "missing banner" warning)
    assert "generated by dotagent" in body.lower()
    # Content NOT hollow — brief fallback worked
    assert "Aigent" in body
    assert "Universal AI chat layer" in body


def test_regenerate_dry_run_writes_nothing(tmp_path: Path):
    """--dry-run reports without touching the filesystem."""
    import os
    from click.testing import CliRunner
    from dotagent.cli import main

    paths = Paths(repo=tmp_path)
    scaffold_agent_dir(paths)
    dump_yaml(paths.config, merge_defaults({"project": {"name": "x"}}))
    (tmp_path / ".agent" / ".version").write_text("0.4.0\n")
    dump_yaml(paths.project_plan, {"modules": {"M01": {"state": "planned"}}})

    # Capture pre-state
    scope_existed = paths.project_scope_md.exists()

    runner = CliRunner()
    orig = os.getcwd()
    os.chdir(tmp_path)
    try:
        result = runner.invoke(main, ["project", "regenerate", "--dry-run"],
                               catch_exceptions=False)
    finally:
        os.chdir(orig)

    assert result.exit_code == 0
    assert "[--dry-run]" in result.output
    # File state unchanged
    assert paths.project_scope_md.exists() == scope_existed
