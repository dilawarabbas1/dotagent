def test_active_contract_without_feat_is_still_fail():
    """A LIVE contract missing FEAT must still fail — the rule is alive."""
    modules = [Module(id="M01", name="a", implements_features=["FEAT-01"])]
    contracts = [ContractRef(
        module_id="M01", cycle_n=1, is_frozen=False,
        body=(
            "<!-- anchor: business-traceability -->\n(empty)\n"
            "<!-- anchor: negotiation-log -->\n"
        ),
    )]
    findings = audit_module_to_contract(modules, contracts)
    assert len(findings) == 1
    assert findings[0].severity == "fail"


def test_frozen_contract_without_feat_is_info_not_fail():
    """Frozen = immutable. Demanding edits is wrong. Info, not fail."""
    modules = [Module(id="M01", name="a")]
    contracts = [ContractRef(
        module_id="M01", cycle_n=1, is_frozen=True,
        body=(
            "<!-- anchor: business-traceability -->\n(empty — pre-schema)\n"
            "<!-- anchor: negotiation-log -->\n"
        ),
    )]
    findings = audit_module_to_contract(modules, contracts)
    assert len(findings) == 1
    assert findings[0].severity == "info"
    assert findings[0].code == "frozen-contract-no-feat"


