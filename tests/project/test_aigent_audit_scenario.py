_AIGENT_BRIEF = """# Project brief: Aigent

**Last reviewed:** 2026-05-01  ·  **Brief version:** 2  ·  **Owner:** alice  ·  **Stage:** beta

## Vision (one sentence)
Universal AI chat layer that gets out of users' way.

## Business objectives
- **OBJ-01 · Universal AI chat layer**: 100 paying customers in 90 days
- **OBJ-02 · Cross-tenant isolation**: zero security incidents year one

## Features

### FEAT-01 · Multi-LLM routing
**Serves:** OBJ-01
**Expected outcome:** route prompts to cheapest provider that meets latency
**What it must do:**
- detect available models per tenant
- route by cost + latency budget

### FEAT-02 · Tenant boundary enforcement
**Serves:** OBJ-02
**Expected outcome:** zero cross-tenant data exposure
**What it must do:**
- every query filters by tenant_id

## Hard rules
- **RULE-01 · Tenant isolation** — _why: BUG-014 leak; how: filter every query_
"""


# ---------------------------------------------------------------------------
# Fix 1: parser reads the Aigent-shape brief end-to-end
# ---------------------------------------------------------------------------

def test_aigent_brief_parses_objectives_and_features():
    """The audit-report shape parses cleanly."""
    brief = parse(_AIGENT_BRIEF)
    assert brief.name == "Aigent"
    assert brief.brief_version == 2
    assert len(brief.objectives) == 2
    assert brief.objective_ids == ["OBJ-01", "OBJ-02"]
    assert "Universal AI chat layer" in brief.objectives[0].text
    assert "100 paying customers" in brief.objectives[0].text

    assert len(brief.features) == 2
    assert brief.feature_ids == ["FEAT-01", "FEAT-02"]
    assert brief.features[0].serves == ["OBJ-01"]

    assert len(brief.hard_rules) == 1
    assert brief.hard_rules[0].id == "RULE-01"


# ---------------------------------------------------------------------------
# Fix 3: render_scope() falls back to brief when plan.yaml missing fields
# ---------------------------------------------------------------------------

def test_render_scope_falls_back_to_brief_when_plan_is_thin():
    """A plan.yaml missing name/goal/description/etc. should NOT produce
    an empty SCOPE.md. Brief data fills the gaps."""
    project = Project(name="")  # the layered-tier shape: empty top-level
    brief = parse(_AIGENT_BRIEF)
    scope = render_scope(project, brief=brief)
    # name falls back to brief.name
    assert "Aigent" in scope
    # goal falls back to brief.vision
    assert "Universal AI chat layer" in scope
    # banner present
    assert "generated by dotagent" in scope.lower()


def test_render_scope_works_without_brief_too():
    """If no brief is available, render_scope() still emits a usable file
    with explicit '(unset — add X)' markers — does NOT crash."""
    project = Project(name="")
    scope = render_scope(project, brief=None)
    assert "(unset" in scope
    assert "generated by dotagent" in scope.lower()


